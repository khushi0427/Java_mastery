public class CharArray {
    public static void main(String[] args) {
        char[] chars = { 'J', 'a', 'v', 'a' };
        int[] ints = { 1, 2, 3 };
        String[] strings = { "a", "b" };

        System.out.println(chars);
        System.out.println(ints);
        System.out.println(strings);
        System.out.println("prefix " + chars);
    }
}
